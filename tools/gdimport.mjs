// Import exact copies of Geometry Dash levels.
//
//   node tools/gdimport.mjs path/to/LevelData.plist
//   node tools/gdimport.mjs path/to/export.gmd
//   node tools/gdimport.mjs levels/gd/            # whole directory
//
// Reads the official level data that ships with the game
// (`<install>/Resources/LevelData.plist`, or a .gmd / .gdlvl export) and
// rewrites js/official-levels.js. The game then plays those exact layouts
// instead of the generated approximations, keeping the name, difficulty and
// palette of the matching generated level.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodeLevelString, parseObjects, toEditorLevel } from './gddata.mjs';
import { LEVELS, THEMES } from '../js/level.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
// GD_LEVELS_OUT lets the importer write somewhere else (used by the tests).
const OUT = process.env.GD_LEVELS_OUT || path.join(ROOT, 'js', 'official-levels.js');

// Name -> the generated level, so an import keeps its difficulty and palette.
const META = new Map(LEVELS.map((lv) => [lv.name.toLowerCase(), lv]));

const unescapeXml = (s) =>
  s
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, '&');

function collectFiles(args) {
  const files = [];
  for (const arg of args) {
    const p = path.resolve(arg);
    if (!fs.existsSync(p)) {
      console.error(`no such file or directory: ${arg}`);
      process.exitCode = 1;
      continue;
    }
    if (fs.statSync(p).isDirectory()) {
      for (const f of fs.readdirSync(p).sort()) {
        if (/\.(plist|gmd|gdlvl|txt)$/i.test(f)) files.push(path.join(p, f));
      }
    } else {
      files.push(p);
    }
  }
  return files;
}

/** LevelData.plist holds one <dict> per level with k2 (name) and k4 (data). */
function readPlistEntries(text) {
  const entries = [];
  for (const dict of text.match(/<dict>[\s\S]*?<\/dict>/g) || []) {
    const name = /<key>k2<\/key>\s*<string>([\s\S]*?)<\/string>/.exec(dict);
    const data = /<key>k4<\/key>\s*<string>([\s\S]*?)<\/string>/.exec(dict);
    if (name && data) entries.push({ name: unescapeXml(name[1]).trim(), raw: data[1] });
  }
  return entries;
}

function entriesFor(file) {
  const text = fs.readFileSync(file, 'utf8');
  if (/<key>k2<\/key>/.test(text) && /<key>k4<\/key>/.test(text)) return readPlistEntries(text);
  // A bare level string file: use the file name as the level name.
  return [{ name: path.basename(file).replace(/\.[^.]+$/, ''), raw: text }];
}

const files = collectFiles(process.argv.slice(2));
if (!files.length) {
  console.error('usage: node tools/gdimport.mjs <LevelData.plist | level.gmd | directory> [...]');
  console.error('The file lives in the Geometry Dash install: Resources/LevelData.plist');
  process.exit(1);
}

const records = [];
for (const file of files) {
  for (const entry of entriesFor(file)) {
    const meta = META.get(entry.name.toLowerCase());
    let theme = 'stereo';
    let difficulty = meta ? meta.difficulty : 'Insane';
    const track = meta ? meta.track : 'neon';
    if (meta) {
      const key = Object.keys(THEMES).find((k) => THEMES[k] === meta.theme);
      if (key) theme = key;
    }

    let objects;
    try {
      objects = parseObjects(decodeLevelString(entry.raw));
    } catch (e) {
      console.warn(`skip ${entry.name}: ${e.message}`);
      continue;
    }
    if (!objects.length) {
      console.warn(`skip ${entry.name}: no objects`);
      continue;
    }

    const { data, stats } = toEditorLevel(objects, { name: entry.name, difficulty, theme, track });
    records.push({ name: entry.name, difficulty, theme, track, data });
    console.log(
      `imported ${entry.name.padEnd(24)} ${String(stats.mapped).padStart(6)} objects ` +
        `(${Object.entries(stats.byType).map(([k, v]) => `${k}:${v}`).join(' ')}) ` +
        `${(data.length / 30) | 0} blocks, ${stats.ignored} decorative ignored`
    );
  }
}

if (!records.length) {
  console.error('nothing imported');
  process.exit(1);
}

const body = records
  .map(
    (r) =>
      `  { name: ${JSON.stringify(r.name)}, difficulty: ${JSON.stringify(r.difficulty)}, ` +
      `theme: ${JSON.stringify(r.theme)}, track: ${JSON.stringify(r.track)}, ` +
      `data: ${JSON.stringify(r.data)} },`
  )
  .join('\n');

fs.writeFileSync(
  OUT,
  '// Generated by tools/gdimport.mjs — exact copies imported from Geometry Dash\n' +
    '// level data. Re-run the importer to refresh; do not edit by hand.\n\n' +
    `export const OFFICIAL_LEVELS = [\n${body}\n];\n`
);

console.log(`\nwrote ${records.length} level(s) to ${path.relative(ROOT, OUT) || OUT}`);
